const PRIVATE_SESSION_RULES = '这是私聊：按双方真实身份和当前可见信息回应，尊重隐私边界，不把此处内容擅自带到其他会话。';
const GROUP_SESSION_RULES = '这是群聊：结合消息归属辨清发言人身份，只使用当前群可见且相关的信息，不泄露私聊内容，也不混淆成员。没有合适切入点时可以不说话，不强制回复。';

export function mobileSessionRules({apiOnly = false, kind = 'private'} = {}) {
  if (!apiOnly) return '';
  return MOBILE_DIALOGUE_RULES+'\n'+(kind === 'group' ? GROUP_SESSION_RULES : PRIVATE_SESSION_RULES);
}
